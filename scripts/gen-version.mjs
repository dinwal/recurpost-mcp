// Keeps src/version.ts in sync with package.json so the version reported in the
// MCP handshake cannot drift from the published one. Run by `npm run build`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
writeFileSync(
  join(root, "src/version.ts"),
  `// Generated by scripts/gen-version.mjs. Do not edit.\nexport const VERSION = "${version}";\n`
);
